"""Generate static pole-residue models from the foundry material data.

Run this module to regenerate and format the installed source module::

    python tools/si_220nm_passive/medium_converter.py
"""

import subprocess
from pathlib import Path

import numpy as np
import tidy3d as td
from tidy3d.plugins.dispersion import AdvancedFastFitterParam, FastDispersionFitter

MATERIAL_DATA_DIR = Path(__file__).parent / "material_data"
OUTPUT_FILE = (
    Path(__file__).parents[2]
    / "src"
    / "cornerstone_forge"
    / "si_220nm_passive"
    / "_material_fits.py"
)
MAX_RMS_ERROR = 1e-5


def _fit(
    wvl_um: np.ndarray,
    n_data: np.ndarray,
    wvl_range: tuple[float, float],
) -> tuple[td.PoleResidue, float]:
    """Fit one material and return its model and RMS error."""
    fitter = FastDispersionFitter(wvl_um=wvl_um, n_data=n_data, wvl_range=wvl_range)
    medium, error = fitter.fit(
        max_num_poles=3,
        advanced_param=AdvancedFastFitterParam(show_progress=False),
    )

    return medium, error


def _medium_source(
    name: str,
    medium: td.PoleResidue,
    error: float,
    wvl_range: tuple[float, float],
) -> list[str]:
    """Create the Python source lines for one fitted medium."""
    lines = [
        f"""# RMS error: {error:.2g}
{name} = td.PoleResidue(
    frequency_range=(td.C_0 / {wvl_range[1]!r}, td.C_0 / {wvl_range[0]!r}),
    eps_inf={medium.eps_inf!r},
    poles=[""",
        ", ".join(f"({a}, {b},)" for a, b in medium.poles),
        "])",
    ]
    return lines


def generate_source() -> None:
    """Fit the source data and write the formatted installed source module."""
    data_si = np.loadtxt(MATERIAL_DATA_DIR / "Si.csv", skiprows=1, delimiter=",")
    wvl_um_si = data_si[:, 0]
    n_si = data_si[:, 1]

    data_sio2 = np.loadtxt(MATERIAL_DATA_DIR / "SiO2.csv", skiprows=1, delimiter=",")
    wvl_um_sio2 = data_sio2[:, 0] * 1e-3
    n_sio2 = data_sio2[:, 1]

    wvl_range = (
        float(max(wvl_um_si[0], wvl_um_sio2[0])),
        float(min(wvl_um_si[-1], wvl_um_sio2[-1])),
    )

    medium_si, error_si = _fit(wvl_um_si, n_si, wvl_range)
    medium_sio2, error_sio2 = _fit(wvl_um_sio2, n_sio2, wvl_range)

    errors = {"medium_si": error_si, "medium_sio2": error_sio2}
    for name, error in errors.items():
        if error >= MAX_RMS_ERROR:
            msg = f"{name} fit RMS error {error:.3g} exceeds {MAX_RMS_ERROR:.3g}"
            raise RuntimeError(msg)

    lines = [
        '"""Static pole-residue models generated by ``medium_converter.py``."""',
        "",
        "import tidy3d as td",
        "",
        *_medium_source("medium_si", medium_si, error_si, wvl_range),
        "",
        *_medium_source("medium_sio2", medium_sio2, error_sio2, wvl_range),
        "",
    ]
    OUTPUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    subprocess.run(["ruff", "format", OUTPUT_FILE], check=True)


if __name__ == "__main__":
    td.config.logging.level = "ERROR"
    generate_source()
